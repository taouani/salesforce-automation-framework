/**
 * Generates fixtures.ts file with Playwright fixture definitions
 */
export async function generateTestFixturesFile(outputDir: string): Promise<string> {
  const fileContent = `/**
 * Playwright Test Fixtures
 * Generated by Salesforce Test Automation Framework
 * 
 * This file contains custom Playwright fixtures for Salesforce test automation.
 */

import { test as base } from '@playwright/test';
import { authenticate } from '../utils/salesforce-auth.js';
import * as testDataHelpers from '../utils/test-data-helpers.js';

/**
 * Authentication fixture
 * Provides authenticated Salesforce session
 */
export const authenticatedPage = base.extend<{
  auth: { accessToken: string; instanceUrl: string };
}>({
  auth: async (_context, use) => {
    const auth = await authenticate();
    await use(auth);
  },
});

/**
 * Test data factory fixture
 * Provides access to test data factory functions
 */
export const testData = base.extend<{
  testData: typeof testDataHelpers;
}>({
  testData: async (_context, use) => {
    await use(testDataHelpers);
  },
});

/**
 * Combined fixture with authentication and test data
 */
export const test = authenticatedPage.extend<{
  testData: typeof testDataHelpers;
}>({
  testData: async (_context, use) => {
    await use(testDataHelpers);
  },
});

export { expect } from '@playwright/test';
`;

  const filePath = join(outputDir, 'fixtures', 'test-fixtures.ts');
  await writeGeneratedFile(filePath, fileContent, { format: true, fileType: 'typescript' });
  
  logger.info({ filePath }, 'Generated test fixtures file');
  
  return filePath;
}

