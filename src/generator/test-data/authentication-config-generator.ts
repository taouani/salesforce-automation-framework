/**
 * Authentication configuration generator
 * Generates .env.example and authentication helper files
 */

import { writeFile } from 'fs/promises';
import { join } from 'path';
import { logger } from '../../utils/logger.js';
import { generateAuthenticationHelpers } from './authentication-helpers.js';
import { writeGeneratedFile } from '../file-generator.js';

/**
 * Generates .env.example file with authentication variables
 */
export async function generateEnvExample(outputDir: string): Promise<string> {
  const envExampleContent = `# Salesforce Authentication Configuration

# Option 1: Username/Password Authentication (OAuth 2.0)
SALESFORCE_USERNAME=your-username@example.com
SALESFORCE_PASSWORD=your-password
SALESFORCE_SECURITY_TOKEN=your-security-token
SALESFORCE_LOGIN_URL=https://login.salesforce.com
SALESFORCE_CLIENT_ID=your-client-id
SALESFORCE_CLIENT_SECRET=your-client-secret

# Option 2: JWT Bearer Token Authentication
# SALESFORCE_CLIENT_ID=your-connected-app-client-id
# SALESFORCE_USERNAME=your-username@example.com
# SALESFORCE_JWT_KEY_FILE=path/to/private-key.pem
# SALESFORCE_LOGIN_URL=https://login.salesforce.com

# Option 3: Configured Connection (Direct Access Token)
# SALESFORCE_ACCESS_TOKEN=your-access-token
# SALESFORCE_INSTANCE_URL=https://your-instance.salesforce.com

# API Configuration
SALESFORCE_API_VERSION=v58.0
`;

  const envExamplePath = join(outputDir, '.env.example');
  await writeFile(envExamplePath, envExampleContent, 'utf-8');
  logger.debug({ envExamplePath }, 'Generated .env.example file');
  
  return envExamplePath;
}

/**
 * Generates authentication helper TypeScript file
 */
export async function generateAuthenticationHelperFile(
  outputDir: string,
  authApproach: 'helpers' | 'configuredConnection' | 'both'
): Promise<string> {
  const helpers = generateAuthenticationHelpers(authApproach);
  
  const helperFileContent = `/**
 * Salesforce Authentication Helpers
 * Generated by Salesforce Test Automation Framework
 * 
 * This file contains authentication helper functions for connecting to Salesforce APIs.
 * Choose the authentication method that best fits your setup.
 */

${helpers.map(helper => helper.implementation).join('\n\n')}

/**
 * Default authentication function
 * Uses the configured authentication approach
 */
export async function authenticate(): Promise<{ accessToken: string; instanceUrl: string }> {
  ${authApproach === 'configuredConnection' 
    ? 'return await getConfiguredConnection();'
    : authApproach === 'both'
    ? `// Try configured connection first, fallback to username/password
  if (process.env.SALESFORCE_ACCESS_TOKEN && process.env.SALESFORCE_INSTANCE_URL) {
    return await getConfiguredConnection();
  }
  return await authenticateWithUsernamePassword();`
    : 'return await authenticateWithUsernamePassword();'}
}
`;

  const helperFilePath = join(outputDir, 'utils', 'salesforce-auth.ts');
  await writeGeneratedFile(helperFilePath, helperFileContent, { format: true, fileType: 'typescript' });
  logger.debug({ helperFilePath, authApproach }, 'Generated authentication helper file');
  
  return helperFilePath;
}

/**
 * Generates all authentication configuration files
 */
export async function generateAuthenticationConfig(
  outputDir: string,
  authApproach: 'helpers' | 'configuredConnection' | 'both' = 'both'
): Promise<{ envExamplePath: string; helperFilePath: string }> {
  const envExamplePath = await generateEnvExample(outputDir);
  const helperFilePath = await generateAuthenticationHelperFile(outputDir, authApproach);
  
  logger.info({ outputDir, authApproach }, 'Generated authentication configuration files');
  
  return { envExamplePath, helperFilePath };
}

