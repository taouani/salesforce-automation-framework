/**
 * Test Data Utilities Generator
 * Generates the test-data-helpers.ts file with all factories and helpers
 */

import { join } from 'path';
import { writeGeneratedFile } from '../file-generator.js';
import { logger } from '../../utils/logger.js';
import type {
  TestDataFactoryDefinition,
  TestDataHelperDefinition,
} from '../../types/test-generation.js';
import type { ObjectDefinition } from '../../types/xml-parsed.js';
import {
  generateTestDataFactoriesForObject,
} from './test-data-factory-generator.js';

/**
 * Generates test-data-helpers.ts file with all factories and helpers
 */
export async function generateTestDataUtilitiesFile(
  outputDir: string,
  objects: ObjectDefinition[],
  relationshipMap: Map<string, Array<{ fieldName: string; type: 'MasterDetail' | 'Lookup'; relatedObject: string }>>
): Promise<string> {
  const factories: TestDataFactoryDefinition[] = [];
  const helpers: TestDataHelperDefinition[] = [];
  const cleanupFunctions: TestDataHelperDefinition[] = [];
  
  // Track function names to prevent duplicates
  const factoryNames = new Set<string>();
  const helperNames = new Set<string>();
  const cleanupNames = new Set<string>();

  // Generate factories and helpers for each object
  for (const objectDef of objects) {
    const relationships = relationshipMap.get(objectDef.fullName) || [];
    const { factory, helpers: objectHelpers, cleanup } = generateTestDataFactoriesForObject(
      objectDef,
      relationships
    );
    
    // Only add factory if not already present
    if (!factoryNames.has(factory.functionName)) {
      factories.push(factory);
      factoryNames.add(factory.functionName);
    }
    
    // Only add helpers if not already present
    for (const helper of objectHelpers) {
      if (!helperNames.has(helper.helperName)) {
        helpers.push(helper);
        helperNames.add(helper.helperName);
      }
    }
    
    // Only add cleanup if not already present
    if (!cleanupNames.has(cleanup.helperName)) {
      cleanupFunctions.push(cleanup);
      cleanupNames.add(cleanup.helperName);
    }
  }

  // Build file content
  const fileContent = `/**
 * Test Data Factories and Helpers
 * Generated by Salesforce Test Automation Framework
 * 
 * This file contains factory functions for creating test data using Salesforce REST API.
 * All functions use the Salesforce REST API for fast test data setup.
 */

import { SalesforceRESTAPIClient } from './salesforce-api-client.js';
import { authenticate } from './salesforce-auth.js';

${factories.map(f => f.implementation).join('\n\n')}

${helpers.map(h => h.implementation).join('\n\n')}

${cleanupFunctions.map(c => c.implementation).join('\n\n')}

/**
 * Cleanup helper to delete multiple records
 */
export async function cleanupTestData(recordIds: string[]): Promise<void> {
  const auth = await authenticate();
  const client = new SalesforceRESTAPIClient(auth);
  
  await Promise.all(
    recordIds.map(async (recordId) => {
      // Extract object type from record ID (first 3 characters)
      const objectPrefix = recordId.substring(0, 3);
      // Map prefix to object type (simplified - in real implementation, use proper mapping)
      const objectType = getObjectTypeFromPrefix(objectPrefix);
      if (objectType) {
        await client.deleteRecord(objectType, recordId);
      }
    })
  );
}

/**
 * Helper to get object type from record ID prefix
 * Note: This is a simplified implementation. In production, use a proper mapping.
 */
function getObjectTypeFromPrefix(prefix: string): string | null {
  // Common Salesforce object prefixes
  const prefixMap: Record<string, string> = {
    '001': 'Account',
    '003': 'Contact',
    '00Q': 'Lead',
    '006': 'Opportunity',
    '00T': 'Task',
    '00U': 'Event',
  };
  
  return prefixMap[prefix] || null;
}
`;

  const filePath = join(outputDir, 'utils', 'test-data-helpers.ts');
  await writeGeneratedFile(filePath, fileContent, { format: true, fileType: 'typescript' });
  
  logger.info(
    { filePath, factoryCount: factories.length, helperCount: helpers.length },
    'Generated test data utilities file'
  );
  
  return filePath;
}

