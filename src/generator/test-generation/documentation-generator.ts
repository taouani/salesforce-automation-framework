/**
 * Documentation Generator
 * Generates README and API documentation for generated tests
 */

import { join } from 'path';
import { writeFile, mkdir } from 'fs/promises';
import { logger } from '../../utils/logger.js';

/**
 * Generates README for generated test project
 */
export async function generateTestProjectREADME(
  outputDir: string,
  projectName: string = 'Salesforce Test Automation'
): Promise<string> {
  const readmeContent = `# ${projectName}

This test project was automatically generated by the Salesforce Test Automation Framework.

## Project Structure

\`\`\`
${projectName}/
├── tests/              # Generated test specification files
├── utils/              # Test data factories and helpers
├── fixtures/           # Playwright test fixtures
├── pages/              # Page Object Model classes (if generated)
└── .env.example        # Environment variable template
\`\`\`

## Setup

1. Install dependencies:
   \`\`\`bash
   npm install
   \`\`\`

2. Configure authentication:
   - Copy \`.env.example\` to \`.env\`
   - Fill in your Salesforce credentials

3. Run tests:
   \`\`\`bash
   npx playwright test
   \`\`\`

## Test Data Factories

The \`utils/test-data-helpers.ts\` file contains factory functions for creating test data using Salesforce REST API.

Example usage:
\`\`\`typescript
import { createAccount } from './utils/test-data-helpers.js';

const accountId = await createAccount({
  Name: 'Test Account',
});
\`\`\`

## Test Fixtures

The \`fixtures/test-fixtures.ts\` file provides Playwright fixtures for:
- Authentication
- Test data factories
- Page objects

Example usage:
\`\`\`typescript
import { test, expect } from './fixtures/test-fixtures.js';

test('example test', async ({ page, testData }) => {
  // Use testData to create test records
  const recordId = await testData.createAccount({ Name: 'Test' });
  // Use page for UI interactions
  await page.goto(\`/lightning/r/Account/\${recordId}/view\`);
});
\`\`\`

## Generated Tests

Test files are organized by Salesforce object in the \`tests/\` directory. Each test file includes:
- CRUD operation tests
- Validation rule tests
- Record type tests
- Field validation tests
- Relationship tests

## Documentation

For more information, see the main framework documentation.
`;

  const readmePath = join(outputDir, 'README.md');
  await writeFile(readmePath, readmeContent, 'utf-8');
  logger.info({ readmePath }, 'Generated README');
  
  return readmePath;
}

/**
 * Generates API documentation for test data factories
 */
export async function generateTestDataAPIDocs(outputDir: string): Promise<string> {
  const docsContent = `# Test Data Factory API Documentation

## Overview

Test data factories use Salesforce REST API to create, update, and delete test records efficiently.

## Factory Functions

Each Salesforce object has a corresponding factory function:
- \`create{ObjectName}(data)\` - Creates a record
- \`delete{ObjectName}(recordId)\` - Deletes a record

## Helper Functions

Helper functions for related records:
- \`create{ChildObject}For{ParentObject}(parentId, data)\` - Creates related records

## Cleanup

Use \`cleanupTestData(recordIds)\` to delete multiple records at once.

## Examples

See the generated \`utils/test-data-helpers.ts\` file for implementation details.
`;

  // Ensure docs directory exists
  const docsDir = join(outputDir, 'docs');
  await mkdir(docsDir, { recursive: true });
  
  const docsPath = join(docsDir, 'test-data-api.md');
  await writeFile(docsPath, docsContent, 'utf-8');
  logger.info({ docsPath }, 'Generated API documentation');
  
  return docsPath;
}

/**
 * Generates all documentation files
 */
export async function generateAllDocumentation(
  outputDir: string,
  projectName?: string
): Promise<{ readmePath: string; apiDocsPath: string }> {
  const readmePath = await generateTestProjectREADME(outputDir, projectName);
  const apiDocsPath = await generateTestDataAPIDocs(outputDir);
  
  logger.info({ outputDir }, 'Generated all documentation');
  
  return { readmePath, apiDocsPath };
}

